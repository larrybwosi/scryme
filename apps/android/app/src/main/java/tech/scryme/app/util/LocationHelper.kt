package tech.scryme.app.util

import android.annotation.SuppressLint
import android.content.Context
import android.location.Location
import android.os.Build
import com.google.android.gms.location.LocationServices
import com.google.android.gms.location.Priority
import com.google.android.gms.tasks.CancellationTokenSource
import kotlinx.coroutines.tasks.await

sealed class LocationValidationResult {
    data class Success(val distanceMeters: Float, val location: Location) : LocationValidationResult()
    data class MockLocationDetected(val location: Location) : LocationValidationResult()
    data class OutOfRadius(val distanceMeters: Float, val maxRadiusMeters: Double, val location: Location) : LocationValidationResult()
    data class Error(val message: String) : LocationValidationResult()
}

object LocationHelper {

    /**
     * Retrieves the current high-accuracy device location using FusedLocationProviderClient.
     */
    @SuppressLint("MissingPermission")
    suspend fun getCurrentLocation(context: Context): Location? {
        return try {
            val fusedLocationClient = LocationServices.getFusedLocationProviderClient(context)
            val cancellationTokenSource = CancellationTokenSource()
            fusedLocationClient.getCurrentLocation(
                Priority.PRIORITY_HIGH_ACCURACY,
                cancellationTokenSource.token
            ).await()
        } catch (e: Exception) {
            e.printStackTrace()
            null
        }
    }

    /**
     * Checks whether the provided location was generated by a mock location provider (Fake GPS).
     */
    @Suppress("DEPRECATION")
    fun isMockLocation(location: Location): Boolean {
        return if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.S) {
            location.isMock
        } else {
            location.isFromMockProvider
        }
    }

    /**
     * Calculates the distance in meters between two geographical coordinates.
     */
    fun calculateDistanceMeters(
        startLat: Double,
        startLng: Double,
        endLat: Double,
        endLng: Double
    ): Float {
        val results = FloatArray(1)
        Location.distanceBetween(startLat, startLng, endLat, endLng, results)
        return results[0]
    }

    /**
     * Validates device location against target branch location coordinates and mock location criteria.
     * Default radius threshold is 50.0 meters.
     */
    fun validateCheckInLocation(
        deviceLocation: Location,
        targetLat: Double?,
        targetLng: Double?,
        maxRadiusMeters: Double = 50.0
    ): LocationValidationResult {
        if (isMockLocation(deviceLocation)) {
            return LocationValidationResult.MockLocationDetected(deviceLocation)
        }

        if (targetLat == null || targetLng == null) {
            // If target location has no pinned coordinates, pass with 0.0 distance
            return LocationValidationResult.Success(0f, deviceLocation)
        }

        val distanceMeters = calculateDistanceMeters(
            deviceLocation.latitude,
            deviceLocation.longitude,
            targetLat,
            targetLng
        )

        return if (distanceMeters <= maxRadiusMeters) {
            LocationValidationResult.Success(distanceMeters, deviceLocation)
        } else {
            LocationValidationResult.OutOfRadius(distanceMeters, maxRadiusMeters, deviceLocation)
        }
    }
}
